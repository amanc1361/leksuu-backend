type MediaProcessingJob = coursedomain.MediaProcessingJob

type MediaJobStore interface {
	Enqueue(ctx context.Context, itemID, kind, operation, targetLanguage, payloadSHA256 string, payload json.RawMessage) (*MediaProcessingJob, error)
	List(ctx context.Context, limit int) ([]MediaProcessingJob, error)
	Get(ctx context.Context, id string) (*MediaProcessingJob, error)
	Cancel(ctx context.Context, id string) (*MediaProcessingJob, error)
	Retry(ctx context.Context, id string) (*MediaProcessingJob, error)
	Approve(ctx context.Context, id, expectedPayloadSHA256 string) (*MediaProcessingJob, error)
	ReviseResult(ctx context.Context, id string, expected, replacement json.RawMessage) (*MediaProcessingJob, error)
}

var ErrMediaJobsUnavailable = apperr.New("admin.media_jobs_unavailable", apperr.KindInternal)
var ErrMediaJobConflict = coursedomain.ErrMediaJobConflict

func (s *Service) SetMediaJobs(store MediaJobStore) { s.mediaJobs = store }

func (s *Service) EnqueueTranscodeJob(ctx context.Context, itemID string) (*MediaProcessingJob, error) {
	if s.mediaJobs == nil {
		return nil, ErrMediaJobsUnavailable
	}
	item, err := s.findMediaItem(ctx, itemID)
	if err != nil {
		return nil, err
	}
	if item.Kind != coursedomain.KindVideo && item.Kind != coursedomain.KindMusic {
		return nil, apperr.ErrBadRequest
	}
	var payload struct {
		URL string `json:"url"`
	}
	if json.Unmarshal(item.Payload, &payload) != nil || !strings.Contains(payload.URL, "/media/") {
		return nil, apperr.ErrBadRequest
	}
	hash := sha256.Sum256(item.Payload)
	return s.mediaJobs.Enqueue(ctx, item.ID, item.Kind, "transcode", "", hex.EncodeToString(hash[:]), item.Payload)
}

func (s *Service) EnqueueMediaJob(ctx context.Context, itemID string) (*MediaProcessingJob, error) {
	if s.mediaJobs == nil {
		return nil, ErrMediaJobsUnavailable
	}
	item, err := s.findMediaItem(ctx, itemID)
	if err != nil {
		return nil, err
	}
	if item.Kind != coursedomain.KindStory && item.Kind != coursedomain.KindPodcast && item.Kind != coursedomain.KindVideo && item.Kind != coursedomain.KindMusic {
		return nil, apperr.ErrBadRequest
	}
	var payload struct {
		URL             string `json:"url"`
		AudioSHA256     string `json:"audio_sha256"`
		Language        string `json:"language"`
		AlignmentSource struct {
			URL             string   `json:"url"`
			AudioSHA256     string   `json:"audio_sha256"`
			Language        string   `json:"language"`
			TranscriptTexts []string `json:"transcript_texts"`
		} `json:"alignment_source"`
		TimingStatus     string `json:"timing_status"`
		AlignmentVersion int    `json:"alignment_version"`
		Transcript       []struct {
			Text         string            `json:"text"`
			Start        *float64          `json:"start"`
			End          *float64          `json:"end"`
			TimingStatus string            `json:"timing_status"`
			Words        []MediaWordTiming `json:"words"`
		} `json:"transcript"`
	}
	if json.Unmarshal(item.Payload, &payload) != nil || strings.TrimSpace(payload.URL) == "" {
		return nil, apperr.ErrBadRequest
	}
	if len(payload.Transcript) > 0 {
		texts := make([]string, len(payload.Transcript))
		allExact := true
		for i, cue := range payload.Transcript {
			texts[i] = cue.Text
			if cue.TimingStatus == "not_in_audio" {
				continue
			}
			allExact = allExact && exactMediaWordTiming(cue.Text, cue.Start, cue.End, cue.Words)
		}
		if allExact || (payload.AlignmentVersion >= 2 && payload.AlignmentSource.URL == payload.URL &&
			payload.AlignmentSource.AudioSHA256 == payload.AudioSHA256 &&
			payload.AlignmentSource.Language == payload.Language &&
			len(payload.AlignmentSource.TranscriptTexts) == len(texts) &&
			stringSliceEqual(payload.AlignmentSource.TranscriptTexts, texts)) {
			return nil, ErrMediaJobConflict
		}
	}
	// Missing transcripts can be generated by the worker. Existing timed cues
	// are revalidated there and returned as a draft, never silently overwritten.
	hash := sha256.Sum256(item.Payload)
	return s.mediaJobs.Enqueue(ctx, item.ID, item.Kind, "synchronize", "", hex.EncodeToString(hash[:]), item.Payload)
}

func exactMediaWordTiming(text string, start, end *float64, words []MediaWordTiming) bool {
	if start == nil || end == nil || math.IsNaN(*start) || math.IsNaN(*end) ||
		math.IsInf(*start, 0) || math.IsInf(*end, 0) || *start < 0 || *end <= *start {
		return false
	}
	tokens := 0
	for _, field := range strings.Fields(text) {
		if strings.IndexFunc(field, unicode.IsLetter) >= 0 {
			tokens++
		}
	}
	if tokens == 0 || len(words) != tokens {
		return false
	}
	previous := *start
	for _, word := range words {
		if math.IsNaN(word.Start) || math.IsNaN(word.End) || math.IsInf(word.Start, 0) || math.IsInf(word.End, 0) ||
			word.Start < previous || word.End <= word.Start || word.Start < *start || word.End > *end+0.05 {
			return false
		}
		previous = word.End
	}
	return true
}

func stringSliceEqual(a, b []string) bool {
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}

func translationSourceHash(payload json.RawMessage) (string, error) {
	var source struct {
		Language    string `json:"language"`
		SourceID    string `json:"source_id"`
		URL         string `json:"url"`
		AudioSHA256 string `json:"audio_sha256"`
		Transcript  []struct {
			Text string `json:"text"`
		} `json:"transcript"`
	}
	if json.Unmarshal(payload, &source) != nil || len(source.Transcript) == 0 {
		return "", apperr.ErrBadRequest
	}
	for _, cue := range source.Transcript {
		if strings.TrimSpace(cue.Text) == "" {
			return "", apperr.ErrBadRequest
		}
	}
	data, err := json.Marshal(source)
	if err != nil {
		return "", err
	}
	hash := sha256.Sum256(data)
	return hex.EncodeToString(hash[:]), nil
}

// EnqueueTranslationJob creates draft generation work only for missing cues.
// Existing draft and approved translations are intentionally never regenerated.
func (s *Service) EnqueueTranslationJob(ctx context.Context, itemID, targetLanguage string) (*MediaProcessingJob, error) {
	if s.mediaJobs == nil {
		return nil, ErrMediaJobsUnavailable
	}
	allowed := os.Getenv("MEDIA_TRANSLATION_TARGETS")
	if allowed == "" {
		allowed = "fa,ckb"
	}
	supported := false
	for _, value := range strings.Split(allowed, ",") {
		if strings.TrimSpace(value) == targetLanguage {
			supported = true
			break
		}
	}
	if !supported || len(targetLanguage) < 2 || len(targetLanguage) > 3 {
		return nil, apperr.ErrBadRequest
	}
	item, err := s.findMediaItem(ctx, itemID)
	if err != nil {
		return nil, err
	}
	if item.Kind != coursedomain.KindStory && item.Kind != coursedomain.KindPodcast && item.Kind != coursedomain.KindVideo && item.Kind != coursedomain.KindMusic {
		return nil, apperr.ErrBadRequest
	}
	var payload struct {
		TranslationStatus map[string]string `json:"translation_status"`
		Transcript        []struct {
			Text        string            `json:"text"`
			Translation map[string]string `json:"translation"`
		} `json:"transcript"`
	}
	if json.Unmarshal(item.Payload, &payload) != nil || len(payload.Transcript) == 0 || len(payload.Transcript) > 2000 {
		return nil, apperr.ErrBadRequest
	}
	if payload.TranslationStatus[targetLanguage] == "approved" || payload.TranslationStatus[targetLanguage] == "human_approved" {
		return nil, ErrMediaJobConflict
	}
	missing := false
	characters := 0
	for _, cue := range payload.Transcript {
		characters += len(cue.Text)
		if strings.TrimSpace(cue.Translation[targetLanguage]) == "" {
			missing = true
		}
	}
	if !missing || characters > 100000 {
		return nil, ErrMediaJobConflict
	}
	hash, err := translationSourceHash(item.Payload)
	if err != nil {
		return nil, err
	}
	return s.mediaJobs.Enqueue(ctx, item.ID, item.Kind, "translate", targetLanguage, hash, item.Payload)
}


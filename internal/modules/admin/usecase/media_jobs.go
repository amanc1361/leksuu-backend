package usecase

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"os"
	"strings"

	coursedomain "github.com/leksuu/platform/internal/modules/course/domain"
	"github.com/leksuu/platform/internal/shared/apperr"
)

type MediaProcessingJob = coursedomain.MediaProcessingJob

type MediaJobStore interface {
	Enqueue(ctx context.Context, itemID, kind, operation, targetLanguage, payloadSHA256 string, payload json.RawMessage) (*MediaProcessingJob, error)
	List(ctx context.Context, limit int) ([]MediaProcessingJob, error)
	Get(ctx context.Context, id string) (*MediaProcessingJob, error)
	Cancel(ctx context.Context, id string) (*MediaProcessingJob, error)
	Retry(ctx context.Context, id string) (*MediaProcessingJob, error)
	Approve(ctx context.Context, id, expectedPayloadSHA256 string) (*MediaProcessingJob, error)
	ReviseResult(ctx context.Context, id string, expected, replacement json.RawMessage) (*MediaProcessingJob, error)
}

var ErrMediaJobsUnavailable = apperr.New("admin.media_jobs_unavailable", apperr.KindInternal)
var ErrMediaJobConflict = coursedomain.ErrMediaJobConflict

func (s *Service) SetMediaJobs(store MediaJobStore) { s.mediaJobs = store }

func (s *Service) EnqueueMediaJob(ctx context.Context, itemID string) (*MediaProcessingJob, error) {
	if s.mediaJobs == nil {
		return nil, ErrMediaJobsUnavailable
	}
	item, err := s.findMediaItem(ctx, itemID)
	if err != nil {
		return nil, err
	}
	if item.Kind != coursedomain.KindStory && item.Kind != coursedomain.KindPodcast && item.Kind != coursedomain.KindVideo {
		return nil, apperr.ErrBadRequest
	}
	var payload struct {
		URL        string `json:"url"`
		Transcript []struct {
			Text string `json:"text"`
		} `json:"transcript"`
	}
	if json.Unmarshal(item.Payload, &payload) != nil || strings.TrimSpace(payload.URL) == "" {
		return nil, apperr.ErrBadRequest
	}
	// Missing transcripts can be generated by the worker. Existing timed cues
	// are revalidated there and returned as a draft, never silently overwritten.
	hash := sha256.Sum256(item.Payload)
	return s.mediaJobs.Enqueue(ctx, item.ID, item.Kind, "synchronize", "", hex.EncodeToString(hash[:]), item.Payload)
}

func translationSourceHash(payload json.RawMessage) (string, error) {
	var source struct {
		Language    string `json:"language"`
		SourceID    string `json:"source_id"`
		URL         string `json:"url"`
		AudioSHA256 string `json:"audio_sha256"`
		Transcript  []struct {
			Text string `json:"text"`
		} `json:"transcript"`
	}
	if json.Unmarshal(payload, &source) != nil || len(source.Transcript) == 0 {
		return "", apperr.ErrBadRequest
	}
	for _, cue := range source.Transcript {
		if strings.TrimSpace(cue.Text) == "" {
			return "", apperr.ErrBadRequest
		}
	}
	data, err := json.Marshal(source)
	if err != nil {
		return "", err
	}
	hash := sha256.Sum256(data)
	return hex.EncodeToString(hash[:]), nil
}

// EnqueueTranslationJob creates draft generation work only for missing cues.
// Existing draft and approved translations are intentionally never regenerated.
func (s *Service) EnqueueTranslationJob(ctx context.Context, itemID, targetLanguage string) (*MediaProcessingJob, error) {
	if s.mediaJobs == nil {
		return nil, ErrMediaJobsUnavailable
	}
	allowed := os.Getenv("MEDIA_TRANSLATION_TARGETS")
	if allowed == "" {
		allowed = "fa,ckb"
	}
	supported := false
	for _, value := range strings.Split(allowed, ",") {
		if strings.TrimSpace(value) == targetLanguage {
			supported = true
			break
		}
	}
	if !supported || len(targetLanguage) < 2 || len(targetLanguage) > 3 {
		return nil, apperr.ErrBadRequest
	}
	item, err := s.findMediaItem(ctx, itemID)
	if err != nil {
		return nil, err
	}
	if item.Kind != coursedomain.KindStory && item.Kind != coursedomain.KindPodcast && item.Kind != coursedomain.KindVideo {
		return nil, apperr.ErrBadRequest
	}
	var payload struct {
		TranslationStatus map[string]string `json:"translation_status"`
		Transcript        []struct {
			Text        string            `json:"text"`
			Translation map[string]string `json:"translation"`
		} `json:"transcript"`
	}
	if json.Unmarshal(item.Payload, &payload) != nil || len(payload.Transcript) == 0 || len(payload.Transcript) > 120 {
		return nil, apperr.ErrBadRequest
	}
	if payload.TranslationStatus[targetLanguage] == "approved" || payload.TranslationStatus[targetLanguage] == "human_approved" {
		return nil, ErrMediaJobConflict
	}
	missing := false
	characters := 0
	for _, cue := range payload.Transcript {
		characters += len(cue.Text)
		if strings.TrimSpace(cue.Translation[targetLanguage]) == "" {
			missing = true
		}
	}
	if !missing || characters > 100000 {
		return nil, ErrMediaJobConflict
	}
	hash, err := translationSourceHash(item.Payload)
	if err != nil {
		return nil, err
	}
	return s.mediaJobs.Enqueue(ctx, item.ID, item.Kind, "translate", targetLanguage, hash, item.Payload)
}

func (s *Service) ListMediaJobs(ctx context.Context) ([]MediaProcessingJob, error) {
	if s.mediaJobs == nil {
		return nil, ErrMediaJobsUnavailable
	}
	return s.mediaJobs.List(ctx, 100)
}

func (s *Service) MediaJob(ctx context.Context, id string) (*MediaProcessingJob, error) {
	if s.mediaJobs == nil {
		return nil, ErrMediaJobsUnavailable
	}
	return s.mediaJobs.Get(ctx, id)
}

func (s *Service) CancelMediaJob(ctx context.Context, id string) (*MediaProcessingJob, error) {
	if s.mediaJobs == nil {
		return nil, ErrMediaJobsUnavailable
	}
	return s.mediaJobs.Cancel(ctx, id)
}

func (s *Service) RetryMediaJob(ctx context.Context, id string) (*MediaProcessingJob, error) {
	if s.mediaJobs == nil {
		return nil, ErrMediaJobsUnavailable
	}
	job, err := s.mediaJobs.Get(ctx, id)
	if err != nil {
		return nil, err
	}
	item, err := s.findMediaItem(ctx, job.ItemID)
	if err != nil {
		return nil, err
	}
	hash := ""
	if job.Operation == "translate" {
		hash, err = translationSourceHash(item.Payload)
		if err != nil {
			return nil, err
		}
	} else {
		digest := sha256.Sum256(item.Payload)
		hash = hex.EncodeToString(digest[:])
	}
	if hash != job.PayloadSHA256 {
		return nil, ErrMediaJobConflict
	}
	return s.mediaJobs.Retry(ctx, id)
}

// ApproveMediaJob applies only validated cue timing to the unchanged payload.
// Any transcript, audio or other metadata edit since enqueue blocks approval.
func (s *Service) ApproveMediaJob(ctx context.Context, id string) (*MediaProcessingJob, error) {
	if s.mediaJobs == nil {
		return nil, ErrMediaJobsUnavailable
	}
	job, err := s.mediaJobs.Get(ctx, id)
	if err != nil {
		return nil, err
	}
	if job.Status != "review" {
		return nil, ErrMediaJobConflict
	}
	if job.Operation == "translate" {
		return s.applyTranslationJob(ctx, job)
	}
	item, err := s.findMediaItem(ctx, job.ItemID)
	if err != nil {
		return nil, err
	}
	hash := sha256.Sum256(item.Payload)
	if hex.EncodeToString(hash[:]) != job.PayloadSHA256 {
		return nil, ErrMediaJobConflict
	}
	var result struct {
		AudioSHA256 string           `json:"audio_sha256"`
		Cues        []StoryTimingCue `json:"cues"`
	}
	if json.Unmarshal(job.Result, &result) != nil || len(result.Cues) == 0 {
		return nil, ErrMediaJobConflict
	}
	var payload map[string]json.RawMessage
	if json.Unmarshal(item.Payload, &payload) != nil {
		return nil, ErrMediaJobConflict
	}
	var original []map[string]json.RawMessage
	if json.Unmarshal(payload["transcript"], &original) != nil {
		return nil, ErrMediaJobConflict
	}
	generatedTranscript := len(original) == 0
	if generatedTranscript {
		original = make([]map[string]json.RawMessage, len(result.Cues))
		for i := range original {
			original[i] = map[string]json.RawMessage{}
		}
	} else if len(original) != len(result.Cues) {
		return nil, ErrMediaJobConflict
	}
	var storedSHA string
	_ = json.Unmarshal(payload["audio_sha256"], &storedSHA)
	if storedSHA != "" && !strings.EqualFold(storedSHA, result.AudioSHA256) {
		return nil, ErrMediaJobConflict
	}
	lastEnd := 0.0
	untimed := 0
	for i, cue := range result.Cues {
		var text string
		if cue.Text == "" {
			return nil, ErrMediaJobConflict
		}
		if generatedTranscript {
			original[i]["text"], _ = json.Marshal(cue.Text)
		} else if json.Unmarshal(original[i]["text"], &text) != nil || text != cue.Text {
			return nil, ErrMediaJobConflict
		}
		if cue.Start == nil || cue.End == nil {
			if cue.Start != nil || cue.End != nil || (cue.TimingStatus != "unverified" && cue.TimingStatus != "not_in_audio") {
				return nil, ErrMediaJobConflict
			}
			untimed++
			if generatedTranscript {
				original[i]["timing_status"], _ = json.Marshal(cue.TimingStatus)
			}
			continue
		}
		if *cue.Start < lastEnd || *cue.End <= *cue.Start {
			return nil, ErrMediaJobConflict
		}
		lastEnd = *cue.End
		// Existing accepted timing is immutable through this queue.
		if existingStart, exists := original[i]["start"]; exists {
			var existingEnd, oldStart float64
			if json.Unmarshal(existingStart, &oldStart) != nil || json.Unmarshal(original[i]["end"], &existingEnd) != nil || oldStart != *cue.Start || existingEnd != *cue.End {
				return nil, ErrMediaJobConflict
			}
			continue
		}
		original[i]["start"], _ = json.Marshal(*cue.Start)
		original[i]["end"], _ = json.Marshal(*cue.End)
		delete(original[i], "timing_status")
	}
	if generatedTranscript {
		payload["transcript_status"], _ = json.Marshal("approved")
	}
	if untimed > 0 {
		payload["timing_status"], _ = json.Marshal("partial_reviewed")
	} else {
		payload["timing_status"], _ = json.Marshal("approved")
	}
	if storedSHA == "" {
		payload["audio_sha256"], _ = json.Marshal(result.AudioSHA256)
	}
	payload["transcript"], _ = json.Marshal(original)
	replacement, err := json.Marshal(payload)
	if err != nil {
		return nil, err
	}
	updated, err := s.repo.UpdateItemPayloadIfUnchanged(ctx, item.ID, item.Payload, replacement)
	if err != nil {
		return nil, err
	}
	if !updated {
		return nil, ErrMediaJobConflict
	}
	return s.mediaJobs.Approve(ctx, id, job.PayloadSHA256)
}

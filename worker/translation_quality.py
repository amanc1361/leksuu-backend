"""Conservative, independently authored reference gate for machine translation.

The fixture is editorial evidence, not generated by the model under test. A
missing or inadequate fixture leaves every new translation as a draft.
"""
import difflib
import hashlib
import json
import re
import unicodedata
from pathlib import Path


def normalized(value):
    return " ".join(unicodedata.normalize("NFKC", value).casefold().split())


def canonicalize_persian(value):
    """Normalize common Arabic codepoints in machine-generated Persian only."""
    return value.translate(str.maketrans({"ي": "ی", "ك": "ک"}))


def candidate_risks(source, translation, target, backtranslation=""):
    """Flag observable defects; an empty list never constitutes semantic approval."""
    if target not in ("fa", "ckb"):
        return ["unsupported_target"]
    risks = []
    letters = [character for character in translation if character.isalpha()]
    if letters and sum("\u0600" <= character <= "\u08ff" for character in letters) / len(letters) < .7:
        risks.append("wrong_script")
    if re.search(r"\bpiece of cake\b", source, re.I) and re.search(r"کیک|کێک", translation):
        risks.append("literal_idiom")
    clauses = [part.strip() for part in re.split(r"[.!?؟،,؛;]+", translation) if part.strip()]
    token_sets = [set(re.findall(r"[^\W_]+", normalized(part).replace("ر", "ڕ"))) for part in clauses]
    for left in range(len(token_sets)):
        for right in range(left + 1, len(token_sets)):
            a, b = token_sets[left], token_sets[right]
            shared = {token for token in a & b if len(token) >= 3}
            repeated = (len(a & b) / max(1, len(a | b)) >= .6 or
                        (len(source.split()) <= 12 and not re.search(r"[,;]", source) and
                         len(shared) >= 2 and len(shared) / max(1, min(len(a), len(b))) >= .4))
            if min(len(a), len(b)) >= 4 and repeated:
                risks.append("repeated_proposition")
                break
        if "repeated_proposition" in risks:
            break
    source_clauses = [part for part in re.split(r"[.!?؟،,؛;]+", source) if part.strip()]
    if (len(source.split()) <= 12 and not re.search(r"[,;]", source) and
            len(clauses) > len(source_clauses) and len(clauses) >= 3):
        risks.append("possible_added_clause")
    if target == "fa" and ("ي" in translation or "ك" in translation):
        risks.append("persian_orthography")
    if backtranslation:
        source_numbers = set(re.findall(r"\d+", source))
        restored_numbers = set(re.findall(r"\d+", backtranslation))
        if source_numbers != restored_numbers:
            risks.append("number_mismatch")
        pairs = (("mice", "mouse"), ("people", "person"), ("children", "child"))
        source_words = set(re.findall(r"[a-z]+", source.lower()))
        restored_words = set(re.findall(r"[a-z]+", backtranslation.lower()))
        if any(plural in source_words and singular in restored_words and plural not in restored_words
               for plural, singular in pairs):
            risks.append("possible_plurality_loss")
        if bool(re.search(r"\b(?:no|not|never|n't)\b", source, re.I)) != bool(
                re.search(r"\b(?:no|not|never|n't)\b", backtranslation, re.I)):
            risks.append("negation_mismatch")
        common_starts = {"I", "We", "You", "He", "She", "It", "They", "The", "A", "An",
                         "This", "That", "Wait", "Please", "Where", "When", "What", "If"}
        source_names = {name.casefold() for name in re.findall(r"\b[A-Z][a-z]{2,}\b", source)
                        if name not in common_starts}
        restored_names = {name.casefold() for name in re.findall(r"\b[A-Z][a-z]{2,}\b", backtranslation)}
        if source_names - restored_names:
            risks.append("proper_noun_mismatch")
    return risks


def evaluate_reference_file(path, target, translate):
    if target not in ("fa", "ckb") or not path:
        return {"passed": False, "reason": "independent_references_unavailable"}
    source = Path(path)
    if not source.is_file():
        return {"passed": False, "reason": "independent_references_unavailable"}
    raw = source.read_bytes()
    if len(raw) > 1_000_000:
        return {"passed": False, "reason": "reference_file_too_large"}
    try:
        fixture = json.loads(raw)
        cases = fixture["cases"]
    except (ValueError, KeyError, TypeError):
        return {"passed": False, "reason": "invalid_reference_file"}
    if fixture.get("version") != 1 or fixture.get("provenance") != "independent_editorial_reference" or \
            not isinstance(cases, list) or len(cases) < 12:
        return {"passed": False, "reason": "insufficient_independent_references"}
    seen = set()
    scores = []
    for case in cases:
        if not isinstance(case, dict) or case.get("source_language") != "en":
            return {"passed": False, "reason": "invalid_reference_case"}
        original, reference = case.get("source"), case.get(target)
        if not isinstance(original, str) or not isinstance(reference, str) or \
                not original.strip() or not reference.strip() or original in seen:
            return {"passed": False, "reason": "invalid_reference_case"}
        seen.add(original)
        candidate = translate(original, target)
        scores.append(difflib.SequenceMatcher(None, normalized(candidate), normalized(reference),
                                              autojunk=False).ratio())
    return {"passed": min(scores) >= .72 and sum(scores) / len(scores) >= .88,
            "minimum_similarity": round(min(scores), 4),
            "mean_similarity": round(sum(scores) / len(scores), 4),
            "case_count": len(scores), "reference_sha256": hashlib.sha256(raw).hexdigest(),
            "method": "independent_editorial_reference_similarity_v1"}
